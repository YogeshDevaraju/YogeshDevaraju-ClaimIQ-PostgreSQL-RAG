def sqlite_table_exists(
    connection,
    table_name,
):
    result = connection.execute(
        """
        SELECT 1
        FROM sqlite_master
        WHERE type = 'table'
          AND name = ?
        """,
        (table_name,),
    ).fetchone()

    return result is not None


def parse_datetime(value):
    if value is None:
        return None

    if isinstance(value, datetime):
        return value

    text_value = str(value).strip()

    if text_value.endswith("Z"):
        text_value = (
            text_value[:-1]
            + "+00:00"
        )

    return datetime.fromisoformat(
        text_value
    )


def parse_date(value):
    if value is None:
        return None

    if (
        isinstance(value, date)
        and not isinstance(value, datetime)
    ):
        return value

    return date.fromisoformat(
        str(value).strip()[:10]
    )


def parse_json(value):
    if value is None:
        return None

    if isinstance(
        value,
        (dict, list),
    ):
        return value

    return json.loads(value)


def convert_value(
    value,
    column,
):
    if value is None:
        return None

    if isinstance(
        column.type,
        Boolean,
    ):
        return bool(value)

    if isinstance(
        column.type,
        DateTime,
    ):
        return parse_datetime(value)

    if isinstance(
        column.type,
        Date,
    ):
        return parse_date(value)

    if isinstance(
        column.type,
        (JSON, JSONB),
    ):
        return parse_json(value)

    return value


def fetch_sqlite_rows(
    connection,
    table_name,
):
    safe_table_name = (
        table_name.replace(
            '"',
            '""',
        )
    )

    query = (
        f'SELECT * '
        f'FROM "{safe_table_name}"'
    )

    return connection.execute(
        query
    ).fetchall()


def ensure_destination_is_empty(
    connection,
    table_names,
):
    metadata = MetaData()
    non_empty_tables = []

    for table_name in table_names:
        table = Table(
            table_name,
            metadata,
            autoload_with=connection,
        )

        count_query = text(
            f'SELECT COUNT(*) '
            f'FROM "{table_name}"'
        )

        row_count = connection.execute(
            count_query
        ).scalar_one()

        if row_count:
            non_empty_tables.append(
                f"{table_name}={row_count}"
            )

    if non_empty_tables:
        raise SystemExit(
            "Migration stopped because "
            "PostgreSQL is not empty: "
            + ", ".join(non_empty_tables)
        )


def migrate_table(
    sqlite_connection,
    postgres_connection,
    table_name,
):
    if not sqlite_table_exists(
        sqlite_connection,
        table_name,
    ):
        print(
            f"SKIP {table_name}: "
            "missing in SQLite"
        )

        return 0

    metadata = MetaData()

    target_table = Table(
        table_name,
        metadata,
        autoload_with=postgres_connection,
    )

    source_rows = fetch_sqlite_rows(
        sqlite_connection,
        table_name,
    )

    target_columns = {
        column.name: column
        for column
        in target_table.columns
    }

    converted_rows = []

    for source_row in source_rows:
        source_data = dict(
            source_row
        )

        target_data = {}

        for (
            column_name,
            column,
        ) in target_columns.items():
            if column_name not in source_data:
                continue

            target_data[column_name] = (
                convert_value(
                    source_data[
                        column_name
                    ],
                    column,
                )
            )

        converted_rows.append(
            target_data
        )

    if converted_rows:
        postgres_connection.execute(
            target_table.insert(),
            converted_rows,
        )

    print(
        f"MIGRATED {table_name}: "
        f"{len(converted_rows)} rows"
    )

    return len(converted_rows)


def reset_identity_sequence(
    connection,
    table_name,
):
    database_inspector = inspect(
        connection
    )

    primary_key_information = (
        database_inspector
        .get_pk_constraint(
            table_name
        )
    )

    primary_key_columns = (
        primary_key_information.get(
            "constrained_columns"
        )
        or []
    )

    if len(primary_key_columns) != 1:
        return

    primary_key_column = (
        primary_key_columns[0]
    )

    sequence_query = text(
        """
        SELECT pg_get_serial_sequence(
            :table_name,
            :column_name
        )
        """
    )

    sequence_name = (
        connection.execute(
            sequence_query,
            {
                "table_name": table_name,
                "column_name": (
                    primary_key_column
                ),
            },
        )
        .scalar_one_or_none()
    )

    if not sequence_name:
        return

    quoted_table = (
        engine.dialect
        .identifier_preparer
        .quote(table_name)
    )

    quoted_column = (
        engine.dialect
        .identifier_preparer
        .quote(primary_key_column)
    )

    maximum_id_query = text(
        f"SELECT MAX({quoted_column}) "
        f"FROM {quoted_table}"
    )

    maximum_id = (
        connection.execute(
            maximum_id_query
        )
        .scalar_one_or_none()
    )

    if maximum_id is None:
        connection.execute(
            text(
                """
                SELECT setval(
                    CAST(:sequence AS regclass),
                    1,
                    false
                )
                """
            ),
            {
                "sequence": (
                    sequence_name
                )
            },
        )

    else:
        connection.execute(
            text(
                """
                SELECT setval(
                    CAST(:sequence AS regclass),
                    :value,
                    true
                )
                """
            ),
            {
                "sequence": (
                    sequence_name
                ),
                "value": int(
                    maximum_id
                ),
            },
        )


def verify_counts(
    sqlite_connection,
    postgres_connection,
    table_names,
):
    print()
    print("COUNT VERIFICATION")
    print("=" * 80)

    all_counts_match = True

    for table_name in table_names:
        if not sqlite_table_exists(
            sqlite_connection,
            table_name,
        ):
            continue

        safe_table_name = (
            table_name.replace(
                '"',
                '""',
            )
        )

        source_count = (
            sqlite_connection.execute(
                f'SELECT COUNT(*) '
                f'FROM "{safe_table_name}"'
            )
            .fetchone()[0]
        )

        quoted_target = (
            engine.dialect
            .identifier_preparer
            .quote(table_name)
        )

        target_count = (
            postgres_connection.execute(
                text(
                    f"SELECT COUNT(*) "
                    f"FROM {quoted_target}"
                )
            )
            .scalar_one()
        )

        if source_count == target_count:
            status = "MATCH"
        else:
            status = "MISMATCH"
            all_counts_match = False

        print(
            f"{table_name:<25} "
            f"SQLite={source_count:<6} "
            f"PostgreSQL={target_count:<6} "
            f"{status}"
        )

    if not all_counts_match:
        raise RuntimeError(
            "Migration count "
            "verification failed."
        )


def main():
    if not SQLITE_PATH.exists():
        raise SystemExit(
            "SQLite backup not found: "
            f"{SQLITE_PATH}"
        )

    if engine.dialect.name != "postgresql":
        raise SystemExit(
            "Destination must be PostgreSQL. "
            f"Current database dialect: "
            f"{engine.dialect.name}"
        )

    sqlite_connection = (
        sqlite3.connect(
            SQLITE_PATH
        )
    )

    sqlite_connection.row_factory = (
        sqlite3.Row
    )

    migrated_tables = list(
        APPLICATION_TABLES
    )

    if sqlite_table_exists(
        sqlite_connection,
        "entity_history",
    ):
        migrated_tables.append(
            "entity_history"
        )

    try:
        with engine.begin() as (
            postgres_connection
        ):
            postgres_inspector = inspect(
                postgres_connection
            )

            available_tables = set(
                postgres_inspector
                .get_table_names()
            )

            missing_tables = [
                table_name
                for table_name
                in APPLICATION_TABLES
                if table_name
                not in available_tables
            ]

            if missing_tables:
                raise SystemExit(
                    "Missing PostgreSQL tables: "
                    + ", ".join(
                        missing_tables
                    )
                    + ". Run: python -m "
                    "src.db.init_db"
                )

            ensure_destination_is_empty(
                postgres_connection,
                APPLICATION_TABLES,
            )

            for table_name in (
                APPLICATION_TABLES
            ):
                migrate_table(
                    sqlite_connection,
                    postgres_connection,
                    table_name,
                )

            if sqlite_table_exists(
                sqlite_connection,
                "entity_history",
            ):
                postgres_connection.execute(
                    text(
                        HISTORY_TABLE_SQL
                    )
                )

                postgres_connection.execute(
                    text(
                        HISTORY_LOOKUP_INDEX_SQL
                    )
                )

                postgres_connection.execute(
                    text(
                        HISTORY_OPERATION_INDEX_SQL
                    )
                )

                migrate_table(
                    sqlite_connection,
                    postgres_connection,
                    "entity_history",
                )

            for table_name in (
                migrated_tables
            ):
                reset_identity_sequence(
                    postgres_connection,
                    table_name,
                )

            verify_counts(
                sqlite_connection,
                postgres_connection,
                migrated_tables,
            )

        print()
        print(
            "SQLite to PostgreSQL migration "
            "completed successfully."
        )

        print(
            f"Source: {SQLITE_PATH}"
        )

        print(
            f"Destination: "
            f"{engine.url.host}:"
            f"{engine.url.port}/"
            f"{engine.url.database}"
        )

        print()

        print(
            "Legacy SQLite table "
            "'user_history' was not migrated "
            "because entity_history is the "
            "common history table."
        )

        print()

        print(
            "Next command: "
            "python -m "
            "scripts.create_all_history"
        )

    finally:
        sqlite_connection.close()


if __name__ == "__main__":
    main()
