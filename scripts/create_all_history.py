from sqlalchemy import inspect, text

from src.db.session import engine


TRACKED_TABLES = [
    "users",
    "policies",
    "claims",
    "claim_notes",
    "claim_status_history",
    "documents",
    "document_chunks",
    "chat_query_logs",
    "audit_logs",
]


HISTORY_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS entity_history (
    history_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    entity_name TEXT NOT NULL,

    entity_id TEXT NOT NULL,

    operation TEXT NOT NULL,

    version INTEGER NOT NULL,

    old_data JSONB,

    new_data JSONB,

    changed_at TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_entity_history_operation
        CHECK (
            operation IN (
                'INSERT',
                'UPDATE',
                'DELETE'
            )
        ),

    CONSTRAINT uq_entity_history_version
        UNIQUE (
            entity_name,
            entity_id,
            version
        )
)
"""


HISTORY_LOOKUP_INDEX_SQL = """
CREATE INDEX IF NOT EXISTS
ix_entity_history_lookup
ON entity_history (
    entity_name,
    entity_id,
    version
)
"""


HISTORY_OPERATION_INDEX_SQL = """
CREATE INDEX IF NOT EXISTS
ix_entity_history_operation
ON entity_history (
    operation
)
"""


TRIGGER_FUNCTION_SQL = """
CREATE OR REPLACE FUNCTION
claimiq_record_entity_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    primary_key_name TEXT := TG_ARGV[0];

    recorded_entity_id TEXT;

    next_version INTEGER;

    previous_data JSONB;

    current_data JSONB;

BEGIN
    IF TG_OP = 'INSERT' THEN
        current_data := to_jsonb(NEW);

        recorded_entity_id := (
            current_data
            ->> primary_key_name
        );

    ELSIF TG_OP = 'UPDATE' THEN
        previous_data := to_jsonb(OLD);

        current_data := to_jsonb(NEW);

        recorded_entity_id := (
            current_data
            ->> primary_key_name
        );

    ELSIF TG_OP = 'DELETE' THEN
        previous_data := to_jsonb(OLD);

        recorded_entity_id := (
            previous_data
            ->> primary_key_name
        );

    ELSE
        RAISE EXCEPTION
            'Unsupported history operation: %',
            TG_OP;
    END IF;


    IF recorded_entity_id IS NULL THEN
        RAISE EXCEPTION
            'Unable to read primary key column '
            '% from table %',
            primary_key_name,
            TG_TABLE_NAME;
    END IF;


    PERFORM pg_advisory_xact_lock(
        hashtextextended(
            TG_TABLE_NAME
            || ':'
            || recorded_entity_id,
            0
        )
    );


    SELECT
        COALESCE(
            MAX(version),
            0
        ) + 1
    INTO next_version
    FROM entity_history
    WHERE entity_name = TG_TABLE_NAME
      AND entity_id = recorded_entity_id;


    INSERT INTO entity_history (
        entity_name,
        entity_id,
        operation,
        version,
        old_data,
        new_data
    )
    VALUES (
        TG_TABLE_NAME,
        recorded_entity_id,
        TG_OP,
        next_version,
        previous_data,
        current_data
    );


    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;


    RETURN NEW;
END;
$$
"""


def quote_identifier(name: str) -> str:
    return (
        engine
        .dialect
        .identifier_preparer
        .quote(name)
    )


def create_history_objects(
    connection,
) -> None:
    connection.execute(
        text(HISTORY_TABLE_SQL)
    )

    connection.execute(
        text(
            HISTORY_LOOKUP_INDEX_SQL
        )
    )

    connection.execute(
        text(
            HISTORY_OPERATION_INDEX_SQL
        )
    )

    connection.execute(
        text(TRIGGER_FUNCTION_SQL)
    )


def get_primary_key(
    inspector,
    table_name: str,
) -> str:
    primary_key_information = (
        inspector.get_pk_constraint(
            table_name
        )
    )

    primary_key_columns = (
        primary_key_information.get(
            "constrained_columns"
        )
        or []
    )

    if len(primary_key_columns) != 1:
        raise ValueError(
            f"Table '{table_name}' must have "
            f"exactly one primary key column. "
            f"Found: {primary_key_columns}"
        )

    return primary_key_columns[0]


def remove_old_triggers(
    connection,
    table_name: str,
) -> None:
    quoted_table = quote_identifier(
        table_name
    )

    trigger_names = [
        "users_after_insert",
        "users_after_update",
        "users_before_delete",
        (
            f"{table_name}"
            f"_history_insert"
        ),
        (
            f"{table_name}"
            f"_history_update"
        ),
        (
            f"{table_name}"
            f"_history_delete"
        ),
        (
            f"{table_name}"
            f"_entity_history"
        ),
    ]

    for trigger_name in trigger_names:
        quoted_trigger = quote_identifier(
            trigger_name
        )

        drop_trigger_sql = (
            f"DROP TRIGGER IF EXISTS "
            f"{quoted_trigger} "
            f"ON {quoted_table}"
        )

        connection.execute(
            text(drop_trigger_sql)
        )


def create_trigger(
    connection,
    table_name: str,
    primary_key: str,
) -> None:
    quoted_table = quote_identifier(
        table_name
    )

    trigger_name = (
        f"{table_name}"
        f"_entity_history"
    )

    quoted_trigger = quote_identifier(
        trigger_name
    )

    primary_key_argument = (
        primary_key.replace(
            "'",
            "''",
        )
    )

    create_trigger_sql = f"""
        CREATE TRIGGER {quoted_trigger}
        AFTER INSERT OR UPDATE OR DELETE
        ON {quoted_table}
        FOR EACH ROW
        EXECUTE FUNCTION
        claimiq_record_entity_history(
            '{primary_key_argument}'
        )
    """

    connection.execute(
        text(create_trigger_sql)
    )


def main() -> None:
    if engine.dialect.name != "postgresql":
        raise SystemExit(
            "This script requires PostgreSQL. "
            f"Current database dialect: "
            f"{engine.dialect.name}"
        )

    tracked_tables = []
    missing_tables = []

    try:
        with engine.begin() as connection:
            create_history_objects(
                connection
            )

            inspector = inspect(
                connection
            )

            available_tables = set(
                inspector.get_table_names()
            )

            for table_name in TRACKED_TABLES:
                if table_name not in available_tables:
                    missing_tables.append(
                        table_name
                    )
                    continue

                primary_key = get_primary_key(
                    inspector,
                    table_name,
                )

                remove_old_triggers(
                    connection,
                    table_name,
                )

                create_trigger(
                    connection,
                    table_name,
                    primary_key,
                )

                tracked_tables.append(
                    table_name
                )

        print()
        print(
            "PostgreSQL history setup "
            "completed successfully."
        )

        print(
            f"Database: "
            f"{engine.url.database}"
        )

        print(
            f"Server: "
            f"{engine.url.host}:"
            f"{engine.url.port}"
        )

        print()
        print("Tracked tables:")

        for table_name in tracked_tables:
            print(
                f"  - {table_name}"
            )

        if missing_tables:
            print()
            print("Missing tables:")

            for table_name in missing_tables:
                print(
                    f"  - {table_name}"
                )

        print()
        print(
            "Future INSERT, UPDATE, and DELETE "
            "operations will be recorded "
            "in entity_history."
        )

    except Exception as exc:
        print()
        print(
            "PostgreSQL history setup failed: "
            f"{exc}"
        )

        raise


if __name__ == "__main__":
    main()